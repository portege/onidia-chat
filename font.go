// fillRect blends a solid rectangle onto dst with alpha compositing, clipped
// to the image bounds.
func fillRect(dst *image.NRGBA, x, y, w, h int, col color.RGBA) {
	if w <= 0 || h <= 0 {
		return
	}
	b := dst.Bounds()
	x0, y0 := max(x, b.Min.X), max(y, b.Min.Y)
	x1, y1 := min(x+w, b.Max.X), min(y+h, b.Max.Y)
	a := uint32(col.A)
	na := 255 - a
	for yy := y0; yy < y1; yy++ {
		i := dst.PixOffset(x0, yy)
		for xx := x0; xx < x1; xx++ {
			d := dst.Pix[i : i+4 : i+4]
			d[0] = uint8((uint32(col.R)*a + uint32(d[0])*na) / 255)
			d[1] = uint8((uint32(col.G)*a + uint32(d[1])*na) / 255)
			d[2] = uint8((uint32(col.B)*a + uint32(d[2])*na) / 255)
			d[3] = uint8(a + uint32(d[3])*na/255)
			i += 4
		}
	}
}

// fillDisc fills a solid circle with a per-pixel distance test.
func fillDisc(img *image.NRGBA, cx, cy, r int, col color.RGBA) {
	x0, y0 := cx-r, cy-r
	rr := float64(r)*float64(r) + 0.5
	for dy := 0; dy <= 2*r; dy++ {
		py := float64(y0+dy-cy) + 0.5
		for dx := 0; dx <= 2*r; dx++ {
			px := float64(x0+dx-cx) + 0.5
			if px*px+py*py <= rr {
				fillRect(img, x0+dx, y0+dy, 1, 1, col)
			}
		}
	}
}

// drawRoundRect fills a rounded rectangle spanning [x,x+w) x [y,y+h).
func drawRoundRect(img *image.NRGBA, x, y, w, h, r int, col color.RGBA) {
	if r > w/2 {
		r = w / 2
	}
	if r > h/2 {
		r = h / 2
	}
	fillRect(img, x+r, y, w-2*r, h, col)     // middle vertical band
	fillRect(img, x, y+r, r, h-2*r, col)     // left band
	fillRect(img, x+w-r, y+r, r, h-2*r, col) // right band
	fillDisc(img, x+r, y+r, r, col)          // four rounded corners
	fillDisc(img, x+w-r-1, y+r, r, col)
	fillDisc(img, x+r, y+h-r-1, r, col)
	fillDisc(img, x+w-r-1, y+h-r-1, r, col)
}

// drawGlyph paints one glyph with its top-left at (x,y); returns the advance.
func drawGlyph(dst *image.NRGBA, x, y int, r rune, scale int, col color.RGBA) int {
	g, ok := font5x7[r]
	if !ok {
		g, ok = font5x7[unicode.ToUpper(r)]
		if !ok {
			return advW * scale // unknown rune: blank, but keep the spacing
		}
	}
	for row := 0; row < glyphH; row++ {
		bits := g[row]
		for cx := 0; cx < glyphW; cx++ {
			if bits&(1<<(glyphW-1-cx)) == 0 {
				continue
			}
			fillRect(dst, x+cx*scale, y+row*scale, scale, scale, col)
		}
	}
	return advW * scale
}

// drawText renders s top-left anchored at (x,y).
func drawText(dst *image.NRGBA, x, y int, s string, scale int, col color.RGBA) {
	px := x
	for _, r := range s {
		px += drawGlyph(dst, px, y, r, scale, col)
	}
}

// textWidth returns the rendered width of s in device pixels.
func textWidth(s string, scale int) int {
	n := utf8.RuneCountInString(s)
	if n == 0 {
		return 0
	}
	return n*advW*scale - scale // no trailing tracking after last glyph
}

// wrapText breaks s into lines of at most cols runes (word wrap; words longer
// than a full line are hard-split; explicit newlines are preserved).
func wrapText(s string, cols int) []string {
	if cols < 1 {
		cols = 1
	}
	var lines []string
	for _, para := range strings.Split(s, "\n") {
		cur := ""
		flush := func() { lines = append(lines, cur); cur = "" }
		for _, word := range strings.Fields(para) {
			wr := []rune(word)
			for len(wr) > 0 {
				if cur == "" {
					take := min(len(wr), cols)
					cur = string(wr[:take])
					wr = wr[take:]
					if len(wr) > 0 {
						flush() // hard-split long word: continue on next line
					}
					continue
				}
				if utf8.RuneCountInString(cur)+1+len(wr) <= cols {
					cur += " " + string(wr)
					wr = nil
					continue
				}
				flush()
			}
		}
		flush()
	}
	return lines
}
